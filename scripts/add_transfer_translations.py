def add_transfer_to_file(locale, transfer_data):
    filepath = os.path.join(BASE_DIR, locale, 'practitioners.json')
    if not os.path.exists(filepath):
        print(f"SKIP: {filepath} not found")
        return

    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if 'transfer' in data:
        print(f"SKIP: {locale} already has transfer key")
        return

    data['transfer'] = transfer_data

    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f"OK: {locale}")


if __name__ == '__main__':
    for locale, trans in TRANSLATIONS.items():
        add_transfer_to_file(locale, trans)
    print("\nDone!")
